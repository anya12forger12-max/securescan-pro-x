def generate_csv_report(report_data: dict[str, Any]) -> str:
    """Generate a CSV report (findings).

    Args:
        report_data: Canonical report data.

    Returns:
        CSV string.
    """
    output = io.StringIO()
    writer = csv.writer(output)

    writer.writerow([
        "Title", "Severity", "Category", "Confidence", "Status",
        "Recommendation", "CVSS", "CWE IDs",
    ])

    for f in report_data.get("findings", []):
        writer.writerow([
            f.get("title", ""),
            f.get("severity", ""),
            f.get("category", ""),
            f.get("confidence", ""),
            f.get("status", ""),
            f.get("recommendation", ""),
            f.get("cvss_score", ""),
            ", ".join(f.get("cwe_ids", [])),
        ])

    return output.getvalue()


# ── Report Service Interface ──────────────────────────────────────


class ReportService(ABC):
    """Interface for report generation operations."""

    @abstractmethod
    async def generate(
        self,
        assessment_id: str,
        format: str = "json",
        assessment: dict[str, Any] | None = None,
        findings: list[dict[str, Any]] | None = None,
        evidence: list[dict[str, Any]] | None = None,
    ) -> dict[str, Any]:
        """Generate a report in the specified format.

        Args:
            assessment_id: Assessment ID.
            format: Output format (json, markdown, html, csv).
            assessment: Assessment data.
            findings: List of findings.
            evidence: List of evidence items.

        Returns:
            Report metadata including content and path.
        """
        ...

    @abstractmethod
    async def list_reports(
        self,
        assessment_id: str,
    ) -> list[dict[str, Any]]:
        """List generated reports for an assessment.

        Args:
            assessment_id: Assessment ID.

        Returns:
            List of report metadata.
        """
        ...


# ── In-Memory Implementation ──────────────────────────────────────


class InMemoryReportService(ReportService):
    """In-memory report service for development and testing."""

    def __init__(self) -> None:
        """Initialize the report store."""
        self._reports: dict[str, list[dict[str, Any]]] = {}
        self._counter: int = 0

    async def generate(
        self,
        assessment_id: str,
        format: str = "json",
        assessment: dict[str, Any] | None = None,
        findings: list[dict[str, Any]] | None = None,
        evidence: list[dict[str, Any]] | None = None,
    ) -> dict[str, Any]:
        """Generate a report.

        Args:
            assessment_id: Assessment ID.
            format: Output format.
            assessment: Assessment data.
            findings: Findings data.
            evidence: Evidence data.

        Returns:
            Report metadata with generated content.
        """
        report_data = build_report_data(
            assessment=assessment or {},
            findings=findings or [],
            evidence=evidence or [],
        )

        generators = {
            "json": generate_json_report,
            "markdown": generate_markdown_report,
            "html": generate_html_report,
            "csv": generate_csv_report,
        }

        generator = generators.get(format)
        if generator is None:
            raise ValueError(f"Unsupported report format: {format}")

        content = generator(report_data)

        self._counter += 1
        now = datetime.now(timezone.utc)
        report_id = f"report-{self._counter:08d}"

        import hashlib
        content_hash = hashlib.sha256(content.encode("utf-8")).hexdigest()

        report = {
            "id": report_id,
            "assessment_id": assessment_id,
            "format": format,
            "title": report_data["report_metadata"]["title"],
            "content": content,
            "content_length": len(content),
            "integrity_hash": content_hash,
            "generated_at": now.isoformat(),
            "generated_by": "report_pipeline",
        }

        self._reports.setdefault(assessment_id, []).append(report)

        logger.info(
            "report.generated",
            report_id=report_id,
            assessment_id=assessment_id,
            format=format,
            content_length=len(content),
        )

        return dict(report)

    async def list_reports(
        self,
        assessment_id: str,
    ) -> list[dict[str, Any]]:
        """List reports for an assessment.

        Args:
            assessment_id: Assessment ID.

        Returns:
            List of report metadata (without content).
        """
        reports = self._reports.get(assessment_id, [])
        # Return metadata only (no content)
        return [
            {k: v for k, v in r.items() if k != "content"}
            for r in reports
        ]
