"""Report pipeline — generates reports from assessment data.

Supports multiple output formats: JSON, Markdown, HTML, and CSV.
Each format has a dedicated generator function that produces a structured
report with executive summary, findings, evidence, recommendations,
timeline, and appendix.
"""

from __future__ import annotations

import csv
import io
import json
from abc import ABC, abstractmethod
from datetime import datetime, timezone
from typing import Any

from app.core.logging import get_logger

logger = get_logger(__name__)


# ── Report Structure ───────────────────────────────────────────────


def build_report_data(
    assessment: dict[str, Any],
    findings: list[dict[str, Any]],
    evidence: list[dict[str, Any]],
    recommendations: list[dict[str, Any]] | None = None,
    timeline: list[dict[str, Any]] | None = None,
    statistics: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Build a canonical report data structure.

    Args:
        assessment: Assessment data.
        findings: List of findings.
        evidence: List of evidence items.
        recommendations: Optional list of recommendations.
        timeline: Optional timeline events.
        statistics: Optional computed statistics.

    Returns:
        Complete report data dictionary.
    """
    severity_summary = {"critical": 0, "high": 0, "medium": 0, "low": 0, "info": 0}
    for f in findings:
        sev = f.get("severity", "info")
        if sev in severity_summary:
            severity_summary[sev] += 1

    executive_summary = (
        f"Assessment '{assessment.get('name', 'Unknown')}' completed with "
        f"{len(findings)} finding(s) and {len(evidence)} evidence item(s). "
        f"Severity distribution: {severity_summary['critical']} critical, "
        f"{severity_summary['high']} high, {severity_summary['medium']} medium, "
        f"{severity_summary['low']} low, {severity_summary['info']} info."
    )

    return {
        "report_metadata": {
            "title": f"Assessment Report: {assessment.get('name', 'Unknown')}",
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "generator": "SecureScan Pro X Report Pipeline",
            "version": "1.0",
        },
        "executive_summary": executive_summary,
        "assessment": {
            "id": assessment.get("id"),
            "name": assessment.get("name"),
            "description": assessment.get("description"),
            "status": assessment.get("status"),
            "priority": assessment.get("priority"),
            "workspace_id": assessment.get("workspace_id"),
            "started_at": assessment.get("started_at"),
            "completed_at": assessment.get("completed_at"),
            "target_count": assessment.get("target_count", 0),
        },
        "findings": findings,
        "severity_summary": severity_summary,
        "evidence": evidence,
        "recommendations": recommendations or [],
        "timeline": timeline or [],
        "statistics": statistics or {},
        "appendix": {
            "tool_version": "0.1.0",
            "report_format_note": "Generated by SecureScan Pro X",
        },
    }


# ── Report Generators ──────────────────────────────────────────────


def generate_json_report(report_data: dict[str, Any]) -> str:
    """Generate a JSON report.

    Args:
        report_data: Canonical report data.

    Returns:
        JSON string.
    """
    return json.dumps(report_data, indent=2, default=str)


def generate_markdown_report(report_data: dict[str, Any]) -> str:
    """Generate a Markdown report.

    Args:
        report_data: Canonical report data.

    Returns:
        Markdown string.
    """
    lines: list[str] = []
    meta = report_data.get("report_metadata", {})
    assessment = report_data.get("assessment", {})
    severity = report_data.get("severity_summary", {})

    lines.append(f"# {meta.get('title', 'Assessment Report')}")
    lines.append("")
    lines.append(f"**Generated:** {meta.get('generated_at', 'N/A')}")
    lines.append(f"**Generator:** {meta.get('generator', 'N/A')}")
    lines.append("")

    lines.append("## Executive Summary")
    lines.append("")
    lines.append(report_data.get("executive_summary", ""))
    lines.append("")

    lines.append("## Assessment Details")
    lines.append("")
    lines.append(f"- **ID:** {assessment.get('id', 'N/A')}")
    lines.append(f"- **Status:** {assessment.get('status', 'N/A')}")
    lines.append(f"- **Priority:** {assessment.get('priority', 'N/A')}")
    lines.append(f"- **Targets:** {assessment.get('target_count', 0)}")
    lines.append(f"- **Started:** {assessment.get('started_at', 'N/A')}")
    lines.append(f"- **Completed:** {assessment.get('completed_at', 'N/A')}")
    lines.append("")

    lines.append("## Severity Summary")
    lines.append("")
    for sev, count in severity.items():
        lines.append(f"- **{sev.upper()}:** {count}")
    lines.append("")

    lines.append("## Findings")
    lines.append("")
    for i, finding in enumerate(report_data.get("findings", []), 1):
        lines.append(f"### {i}. {finding.get('title', 'Untitled')}")
        lines.append("")
        lines.append(f"- **Severity:** {finding.get('severity', 'N/A')}")
        lines.append(f"- **Category:** {finding.get('category', 'N/A')}")
        if finding.get("summary"):
            lines.append(f"- **Summary:** {finding['summary']}")
        if finding.get("recommendation"):
            lines.append(f"- **Recommendation:** {finding['recommendation']}")
        lines.append("")

    lines.append("## Evidence")
    lines.append("")
    for i, ev in enumerate(report_data.get("evidence", []), 1):
        lines.append(f"### {i}. {ev.get('title', 'Untitled')}")
        lines.append(f"- **Type:** {ev.get('evidence_type', 'N/A')}")
        lines.append(f"- **Source:** {ev.get('source', 'N/A')}")
        lines.append(f"- **Classification:** {ev.get('classification', 'N/A')}")
        lines.append("")

    if report_data.get("timeline"):
        lines.append("## Timeline")
        lines.append("")
        for event in report_data["timeline"]:
            lines.append(
                f"- [{event.get('timestamp', 'N/A')}] "
                f"{event.get('title', 'Event')}"
            )
        lines.append("")

    lines.append("## Appendix")
    lines.append("")
    appendix = report_data.get("appendix", {})
    lines.append(f"- **Tool Version:** {appendix.get('tool_version', 'N/A')}")
    lines.append(f"- **Note:** {appendix.get('report_format_note', '')}")

    return "\n".join(lines)


