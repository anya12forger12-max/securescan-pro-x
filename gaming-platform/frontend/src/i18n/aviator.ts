/** Aviator UI translations. Strings live here rather than in components so an
 * operator can add a language without touching game logic. `en` is the base:
 * any missing key in another locale falls back to it. */
export type Locale = 'en' | 'hi' | 'ar';

export const LOCALES: readonly Locale[] = ['en', 'hi', 'ar'];

export const isLocale = (value: unknown): value is Locale =>
  typeof value === 'string' && (LOCALES as readonly string[]).includes(value);

export const localeDirection = (locale: Locale): 'ltr' | 'rtl' => (locale === 'ar' ? 'rtl' : 'ltr');

