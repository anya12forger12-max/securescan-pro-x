const dictionaries: Record<Locale, Dictionary> = { en, hi, ar };

export function translate(
  locale: Locale,
  key: string,
  vars: Record<string, string | number> = {},
): string {
  const template = dictionaries[locale]?.[key] ?? en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_match, name: string) => String(vars[name] ?? ''));
}

export function formatAmount(value: number | string, locale: Locale, currency: string): string {
  const amount = Number(value);
  if (!Number.isFinite(amount)) return '—';
  try {
    return new Intl.NumberFormat(locale, {
      style: 'currency',
      currency,
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    }).format(amount);
  } catch {
    return `${amount.toFixed(2)} ${currency}`;
  }
}

export function formatDate(value: string | number, locale: Locale): string {
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return '—';
  try {
    return new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeStyle: 'short' }).format(date);
  } catch {
    return date.toISOString();
  }
}
