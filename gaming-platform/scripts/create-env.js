import { generateKeyPairSync, randomBytes } from "node:crypto";
import { chmod, readFile, writeFile } from "node:fs/promises";

const force = process.argv.includes("--force");
const origin = process.env.CORS_ORIGIN;

if (!origin || !/^https?:\/\/[^\s]+$/.test(origin)) {
  console.error("Set CORS_ORIGIN to the public browser origin, for example:");
  console.error("  CORS_ORIGIN=https://play.example.com npm run env:init");
  process.exit(1);
}

const envPath = new URL("../.env", import.meta.url);
const secret = (bytes = 32) => randomBytes(bytes).toString("base64url");

// `--force` is an upgrade path, not a license to orphan existing data volumes.
// The stock Postgres/Redis images only honour their passwords when a volume is
// initialised, so reuse the old data-tier credentials when regenerating .env.
const previous = {};
if (force) {
  try {
    const text = await readFile(envPath, "utf8");
    for (const line of text.split("\n")) {
      const match = line.match(/^([A-Z][A-Z0-9_]*)=(.*)$/);
      if (match && !(match[1] in previous)) previous[match[1]] = match[2];
    }
  } catch (err) {
    if (err.code !== "ENOENT") throw err;
  }
}

// A reused data volume is keyed by the credentials in its URL, not by the
// values that happened to be split into separate variables. Derive the
// password/user/database from an existing URL before generating anything new,
// otherwise a `--force` refresh could point the apps at credentials the
// database container was never initialised with.
const previousPostgres = (() => {
  try {
    if (!previous.DATABASE_URL) return null;
    const url = new URL(previous.DATABASE_URL);
    if (url.protocol !== "postgresql:") return null;
    return {
      user: decodeURIComponent(url.username),
      password: decodeURIComponent(url.password),
      database: decodeURIComponent(url.pathname.slice(1)),
    };
  } catch {
    return null;
  }
})();
const previousRedis = (() => {
  try {
    if (!previous.REDIS_URL) return null;
    const url = new URL(previous.REDIS_URL);
    return url.protocol === "redis:" ? decodeURIComponent(url.password) : null;
  } catch {
    return null;
  }
})();
const postgresUser = previous.POSTGRES_USER || previousPostgres?.user || "gp";
const postgresPassword = previous.POSTGRES_PASSWORD || previousPostgres?.password || secret(24);
const postgresDb = previous.POSTGRES_DB || previousPostgres?.database || "gaming_platform";
const databaseUrl = previous.DATABASE_URL
  || `postgresql://${encodeURIComponent(postgresUser)}:${encodeURIComponent(postgresPassword)}@postgres:5432/${encodeURIComponent(postgresDb)}`;
const redisPassword = previous.REDIS_PASSWORD || previousRedis || secret(24);
const redisUrl = previous.REDIS_URL
  || `redis://:${encodeURIComponent(redisPassword)}@redis:6379`;
// Access tokens are RS256-signed: auth holds the private key, every other
// service (and the gateway's jti/version check) only gets the public key. PEM
// text is stored with literal \n escapes so Compose can interpolate one line.
const { publicKey, privateKey } = generateKeyPairSync("rsa", {
  modulusLength: 2048,
  publicKeyEncoding: { type: "spki", format: "pem" },
  privateKeyEncoding: { type: "pkcs8", format: "pem" },
});
const jwtPublicKey = publicKey.replace(/\n/g, "\\n").trim();
const jwtPrivateKey = privateKey.replace(/\n/g, "\\n").trim();
const serviceToken = secret(48);
const adminServiceToken = secret(48);
const walletServiceToken = secret(48);
const walletDebitToken = secret(48);
const walletBonusToken = secret(48);
const walletWinToken = secret(48);
const realtimeServiceToken = secret(48);
const promotionsServiceToken = secret(48);
const crashServiceToken = secret(48);
const bootstrapToken = secret(48);

const contents = `# Generated by scripts/create-env.js on ${new Date().toISOString()}.
# Keep this file out of version control and rotate the secrets to redeploy.
NODE_ENV=production
POSTGRES_USER=${postgresUser}
POSTGRES_PASSWORD=${postgresPassword}
POSTGRES_DB=${postgresDb}
DATABASE_URL=${databaseUrl}
# Per-service Postgres pool size; keep 15 * DB_POOL_MAX below max_connections.
DB_POOL_MAX=5
# Redis is password-protected and reachable only on the Compose internal network.
REDIS_PASSWORD=${redisPassword}
REDIS_URL=${redisUrl}
# RS256 access-token keypair. Regenerating .env invalidates every access token.
JWT_PUBLIC_KEY=${jwtPublicKey}
JWT_PRIVATE_KEY=${jwtPrivateKey}
JWT_ISSUER=gaming-platform
JWT_AUDIENCE=gaming-platform-api
SERVICE_TOKEN=${serviceToken}
# Capability-scoped internal credentials. Never reuse SERVICE_TOKEN for these.
ADMIN_SERVICE_TOKEN=${adminServiceToken}
# WALLET_SERVICE_TOKEN is the full gateway/test/admin capability. The three
# scoped tokens are the only ones handed to peer services in production.
WALLET_SERVICE_TOKEN=${walletServiceToken}
WALLET_DEBIT_SERVICE_TOKEN=${walletDebitToken}
WALLET_BONUS_SERVICE_TOKEN=${walletBonusToken}
WALLET_WIN_SERVICE_TOKEN=${walletWinToken}
REALTIME_SERVICE_TOKEN=${realtimeServiceToken}
PROMOTIONS_SERVICE_TOKEN=${promotionsServiceToken}
CRASH_SERVICE_TOKEN=${crashServiceToken}
# One-time secret for claiming the first admin role via the gateway.
ADMIN_BOOTSTRAP_TOKEN=${bootstrapToken}
CORS_ORIGIN=${origin}
LOG_LEVEL=info
# Edge abuse controls. Fail closed if the shared limiter is unavailable.
RATE_LIMIT_ENABLED=true
RATE_LIMIT_WINDOW_MS=60000
RATE_LIMIT_AUTH_MAX=10
RATE_LIMIT_USER_MAX=120
RATE_LIMIT_MUTATE_MAX=30
RATE_LIMIT_FAIL_CLOSED=true
RATE_LIMIT_STREAM_MAX=20
TRUST_PROXY_HOPS=1
UPSTREAM_TIMEOUT_MS=30000
# Gateway cache for access-token jti/version checks; revocation takes effect
# within this window. 0 disables caching and hits Postgres on every request.
TOKEN_VERSION_CACHE_MS=15000
MAX_STREAMS=500
EVENT_RETENTION_HOURS=168
`;

try {
  await writeFile(envPath, contents, { encoding: "utf8", flag: force ? "w" : "wx" });
  try {
    await chmod(envPath, 0o600);
  } catch (err) {
    // exFAT/FAT mounts (common for the USB-based checkout documented in the
    // README) cannot enforce POSIX modes. Warn instead of pretending the
    // generated secrets are protected.
    console.warn(`[env:init] could not set .env to 0600 (${err.message}); keep the file private`);
  }
  console.log(`[env:init] wrote ${envPath.pathname}`);
  if (force && (previous.POSTGRES_PASSWORD || previous.REDIS_PASSWORD)) {
    console.log("[env:init] kept existing Postgres/Redis credentials for the current volumes");
  }
  console.log("[env:init] review CORS_ORIGIN and keep .env secret");
} catch (err) {
  if (err.code === "EEXIST") {
    console.error("[env:init] .env already exists; pass --force to replace it");
    process.exit(1);
  }
  throw err;
}
