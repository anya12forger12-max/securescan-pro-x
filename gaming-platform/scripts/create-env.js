import { randomBytes } from "node:crypto";
import { chmod, writeFile } from "node:fs/promises";

const force = process.argv.includes("--force");
const origin = process.env.CORS_ORIGIN;

if (!origin || !/^https?:\/\/[^\s]+$/.test(origin)) {
  console.error("Set CORS_ORIGIN to the public browser origin, for example:");
  console.error("  CORS_ORIGIN=https://play.example.com npm run env:init");
  process.exit(1);
}

const envPath = new URL("../.env", import.meta.url);
const secret = (bytes = 32) => randomBytes(bytes).toString("base64url");
const postgresPassword = secret(24);
const jwtSecret = secret(48);
const serviceToken = secret(48);

const contents = `# Generated by scripts/create-env.js on ${new Date().toISOString()}.
# Keep this file out of version control and rotate the secrets to redeploy.
NODE_ENV=production
POSTGRES_USER=gp
POSTGRES_PASSWORD=${postgresPassword}
POSTGRES_DB=gaming_platform
DATABASE_URL=postgresql://gp:${encodeURIComponent(postgresPassword)}@postgres:5432/gaming_platform
REDIS_URL=redis://redis:6379
JWT_ACCESS_SECRET=${jwtSecret}
SERVICE_TOKEN=${serviceToken}
CORS_ORIGIN=${origin}
LOG_LEVEL=info
`;

try {
  await writeFile(envPath, contents, { encoding: "utf8", flag: force ? "w" : "wx" });
  await chmod(envPath, 0o600);
  console.log(`[env:init] wrote ${envPath.pathname}`);
  console.log("[env:init] review CORS_ORIGIN and keep .env secret");
} catch (err) {
  if (err.code === "EEXIST") {
    console.error("[env:init] .env already exists; pass --force to replace it");
    process.exit(1);
  }
  throw err;
}
